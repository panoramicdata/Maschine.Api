	/// <summary>Returns the 4 row-bytes for the given ASCII character (clamped to space on out-of-range).</summary>
	internal static ReadOnlySpan<byte> GetGlyph4x4(char c)
	{
		var idx = c < 0x20 || c > 0x7E ? 0 : c - 0x20;
		var data = Font4x4Glyphs;
		return data.Slice(idx * Font4Height, Font4Height);
	}
