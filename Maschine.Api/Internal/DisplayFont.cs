	/// <summary>Returns the 8 row-bytes for the given ASCII character (clamped to space on out-of-range).</summary>
	internal static ReadOnlySpan<byte> GetGlyph8x8(char c)
	{
		var idx = c < 0x20 || c > 0x7E ? 0 : c - 0x20;
		var data = Font8x8Glyphs;
		return data.Slice(idx * Font8Height, Font8Height);
	}

