function Thin-Byte([byte]$b) {
    $result = $b; $bit = 0
    while ($bit -lt 8) {
        $cur = ($b -shr $bit) -band 1
        if ($cur -eq 0) { $bit++; continue }
        $runLen = 0; $k = $bit
        while ($k -lt 8 -and (($b -shr $k) -band 1) -eq 1) { $runLen++; $k++ }
        if ($runLen -eq 2) { $result = [byte]($result -band (-bnot (1 -shl ($bit + 1)))) }
        $bit += $runLen
    }
    return $result
}

